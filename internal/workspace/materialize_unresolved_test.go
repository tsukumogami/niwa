// TestPromoteThreeWay covers all three arms of the promote branch on the
// instance path: promote a resolved key, omit-and-report a marked one, and keep
// the hard error for a key that is neither — which is what still catches a typo
// in the promote list.
func TestPromoteThreeWay(t *testing.T) {
	t.Run("promotes a resolved key", func(t *testing.T) {
		ctx, _ := unresolvedEnvCtx(t, map[string]config.MaybeSecret{"TOKEN": {Plain: "v"}})
		ctx.Effective.Claude.Env = config.ClaudeEnvConfig{Promote: []string{"TOKEN"}}
		got, _, err := resolveClaudeEnvVars(ctx)
		if err != nil {
			t.Fatalf("resolveClaudeEnvVars: %v", err)
		}
		if got["TOKEN"] != "v" {
			t.Errorf("promoted env = %v", got)
		}
	})

	t.Run("omits and reports a marked key", func(t *testing.T) {
		ctx, _ := unresolvedEnvCtx(t, map[string]config.MaybeSecret{
			"TOKEN": markedSecret(config.CauseProviderUnreachable, config.LevelRequired, "the token"),
		})
		ctx.Effective.Claude.Env = config.ClaudeEnvConfig{Promote: []string{"TOKEN"}}
		keys := keyreport.New()
		ctx.Keys = keys

		got, _, err := resolveClaudeEnvVars(ctx)
		if err != nil {
			t.Fatalf("promotion of an omitted key must not fail: %v", err)
		}
		if _, ok := got["TOKEN"]; ok {
			t.Errorf("omitted key was promoted anyway: %v", got)
		}
		report := keys.Report()
		if len(report) != 1 || report[0].Key != "TOKEN" {
			t.Fatalf("report = %v, want the omitted key", report)
		}
		if report[0].Cause != config.CauseProviderUnreachable || report[0].Level != config.LevelRequired {
			t.Errorf("report entry lost the mark's metadata: %+v", report[0])
		}
	})

	t.Run("errors for a key that is neither", func(t *testing.T) {
		ctx, _ := unresolvedEnvCtx(t, map[string]config.MaybeSecret{"TOKEN": {Plain: "v"}})
		ctx.Effective.Claude.Env = config.ClaudeEnvConfig{Promote: []string{"TYPOD_TOKEN"}}
		if _, _, err := resolveClaudeEnvVars(ctx); err == nil {
			t.Fatal("a promoted key that was never declared must stay a hard error")
		} else if !strings.Contains(err.Error(), "TYPOD_TOKEN") {
			t.Errorf("error = %q, want it to name the key", err)
		}
	})
}

// TestPromoteOmissionIsReportedOnce: the post-merge walk and the promote branch
// see the same shortfall from different angles, and R6 asks for one
// consolidated report rather than one line per producer.
func TestPromoteOmissionIsReportedOnce(t *testing.T) {
	ctx, _ := unresolvedEnvCtx(t, map[string]config.MaybeSecret{
		"TOKEN": markedSecret(config.CauseProviderUnreachable, config.LevelRequired, "the token"),
	})
	ctx.Effective.Claude.Env = config.ClaudeEnvConfig{Promote: []string{"TOKEN"}}
	keys := keyreport.New()
	keys.Add(keyreport.Entry{Scope: "repos.app.env.secrets", Key: "TOKEN", Cause: config.CauseProviderUnreachable})
	ctx.Keys = keys

	if _, _, err := resolveClaudeEnvVars(ctx); err != nil {
		t.Fatalf("resolveClaudeEnvVars: %v", err)
	}
	if report := keys.Report(); len(report) != 1 {
		t.Errorf("report holds %d entries, want one consolidated line: %v", len(report), report)
	}
}

// TestPromoteWorktreePathUsesRecoveredRecords: the worktree path holds no marks
// — it reads an already-materialized file rather than re-resolving — so its
// unresolved set has to come from the records in that file.
func TestPromoteWorktreePathUsesRecoveredRecords(t *testing.T) {
	ctx, _ := unresolvedEnvCtx(t, nil)
	ctx.Effective.Claude.Env = config.ClaudeEnvConfig{Promote: []string{"TOKEN"}}
	ctx.InheritedEnv = map[string]string{"OTHER": "x"}
	ctx.InheritedUnresolved = map[string]unresolvedEnvKey{
		"TOKEN": {Record: envformat.Record{Level: "required", Cause: "provider-unreachable", Description: "the token"}},
	}

	got, _, err := resolveClaudeEnvVars(ctx)
	if err != nil {
		t.Fatalf("worktree promotion of an omitted key must not fail: %v", err)
	}
	if _, ok := got["TOKEN"]; ok {
		t.Errorf("omitted key was promoted: %v", got)
	}

	// A key in neither the inherited env nor the recovered records is still a
	// hard error, so inheritance cannot mask a genuine misconfiguration.
	ctx.Effective.Claude.Env = config.ClaudeEnvConfig{Promote: []string{"ABSENT"}}
	if _, _, err := resolveClaudeEnvVars(ctx); err == nil {
		t.Fatal("expected the promote error for a key absent from config, clone env, and records")
	}
}

// TestReadCloneEnvOutputRecoversRecords wires the reader to the file the
