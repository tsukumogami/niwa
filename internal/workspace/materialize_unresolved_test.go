// markedSecret builds the post-resolver shape of a key the resolver could not
// supply: no value, and a mark carrying why.
func markedSecret(cause config.UnresolvedCause, level config.RequirementLevel, desc string) config.MaybeSecret {
	return config.MaybeSecret{Unresolved: &config.Unresolved{
		Cause:        cause,
		Level:        level,
		Description:  desc,
		ProviderKind: "infisical",
	}}
}

// unresolvedEnvCtx builds a materialize context whose effective env holds the
// given values, with no files or discovery involved.
func unresolvedEnvCtx(t *testing.T, values map[string]config.MaybeSecret) (*MaterializeContext, string) {
	t.Helper()
	tmp := t.TempDir()
	repoDir := filepath.Join(tmp, "repo")
	if err := os.MkdirAll(repoDir, 0o755); err != nil {
		t.Fatal(err)
	}
	return &MaterializeContext{
		Effective: EffectiveConfig{
			Env: config.EnvConfig{Secrets: config.EnvVarsTable{Values: values}},
		},
		RepoName:  "myrepo",
		RepoDir:   repoDir,
		ConfigDir: tmp,
	}, repoDir
}

// TestEnvMaterializerOmitsMarkedKeyAndRecordsIt is the headline behaviour: a
// marked key never appears as an assignment, and its record sits at the sorted
// position the assignment would have occupied.
func TestEnvMaterializerOmitsMarkedKeyAndRecordsIt(t *testing.T) {
	ctx, repoDir := unresolvedEnvCtx(t, map[string]config.MaybeSecret{
		"AAA_FIRST":         {Plain: "one"},
		"ANTHROPIC_API_KEY": markedSecret(config.CauseProviderUnreachable, config.LevelRequired, "API key for Claude Code sessions"),
		"ZZZ_LAST":          {Plain: "two"},
	})

	if _, err := (&EnvMaterializer{}).Materialize(ctx); err != nil {
		t.Fatalf("Materialize: %v", err)
	}

	data, err := os.ReadFile(filepath.Join(repoDir, ".local.env"))
	if err != nil {
		t.Fatalf("reading env file: %v", err)
	}
	want := "# Generated by niwa - do not edit manually\n" +
		"AAA_FIRST=one\n" +
		"# niwa: unresolved ANTHROPIC_API_KEY required provider-unreachable \"API key for Claude Code sessions\"\n" +
		"ZZZ_LAST=two\n"
	if string(data) != want {
		t.Errorf("generated file =\n%s\nwant\n%s", data, want)
	}
	if strings.Contains(string(data), "ANTHROPIC_API_KEY=") {
		t.Error("a marked key must never be written with an empty value")
	}
}

// TestEnvMaterializerWritesFileWhenEveryKeyIsUnresolved covers the empty-map
// blocker. A contributor with no vault access resolves nothing at all, and both
// early returns used to leave that repo with no file and therefore no account of
// what was missing.
func TestEnvMaterializerWritesFileWhenEveryKeyIsUnresolved(t *testing.T) {
	ctx, repoDir := unresolvedEnvCtx(t, map[string]config.MaybeSecret{
		"GITHUB_TOKEN": markedSecret(keyreport.CauseNoSource, config.LevelRequired, "GitHub PAT"),
		"OPENAI_KEY":   markedSecret(config.CauseUndeclaredProvider, config.LevelOptional, ""),
	})

	written, err := (&EnvMaterializer{}).Materialize(ctx)
	if err != nil {
		t.Fatalf("Materialize: %v", err)
	}
	if len(written) != 1 {
		t.Fatalf("expected the env file to be written, got %v", written)
	}

	data, err := os.ReadFile(filepath.Join(repoDir, ".local.env"))
	if err != nil {
		t.Fatalf("reading env file: %v", err)
	}
	for _, key := range []string{"GITHUB_TOKEN", "OPENAI_KEY"} {
		if !strings.Contains(string(data), envformat.RecordPrefix+" "+key+" ") {
			t.Errorf("record for %s missing:\n%s", key, data)
		}
		if strings.Contains(string(data), key+"=") {
			t.Errorf("%s written as an assignment:\n%s", key, data)
		}
	}
}

// TestEnvMaterializerRecordsInJSONAndShell: a non-dotenv target gets the record
// in its own format, and the file stays well-formed in that format.
func TestEnvMaterializerRecordsInJSONAndShell(t *testing.T) {
	ctx, repoDir := unresolvedEnvCtx(t, map[string]config.MaybeSecret{
		"REAL":    {Plain: "value"},
		"MISSING": markedSecret(config.CauseKeyNotFound, config.LevelRequired, "needed for CI"),
	})
	ctx.Config = &config.WorkspaceConfig{
		Repos: map[string]config.RepoOverride{
			"myrepo": {EnvOutput: config.OutputTargets{
				{Path: "secrets.local.json"},
				{Path: "env.local.sh"},
			}},
		},
	}

	if _, err := (&EnvMaterializer{}).Materialize(ctx); err != nil {
		t.Fatalf("Materialize: %v", err)
	}

	jsonData, err := os.ReadFile(filepath.Join(repoDir, "secrets.local.json"))
	if err != nil {
		t.Fatal(err)
	}
	var doc map[string]string
	if err := json.Unmarshal(jsonData, &doc); err != nil {
		t.Fatalf("json target is not a flat string map: %v\n%s", err, jsonData)
	}
	if doc["REAL"] != "value" {
		t.Errorf("json target lost the resolved key: %v", doc)
	}
	if _, ok := doc["MISSING"]; ok {
		t.Errorf("json target wrote the omitted key as a member: %v", doc)
	}
	if got := doc[envformat.RecordPrefix+" MISSING"]; !strings.Contains(got, "key-not-found") {
		t.Errorf("json record member missing or malformed: %v", doc)
	}

	shData, err := os.ReadFile(filepath.Join(repoDir, "env.local.sh"))
	if err != nil {
		t.Fatal(err)
	}
	for _, line := range strings.Split(strings.TrimSuffix(string(shData), "\n"), "\n") {
		if !strings.HasPrefix(line, "#") && !strings.HasPrefix(line, "export ") {
			t.Errorf("shell target line is neither comment nor export: %q", line)
		}
	}
	if !strings.Contains(string(shData), envformat.RecordPrefix+" MISSING required key-not-found") {
		t.Errorf("shell target missing the record:\n%s", shData)
	}
	if strings.Contains(string(shData), "export MISSING=") {
		t.Errorf("shell target exported the omitted key:\n%s", shData)
	}
}

// TestRecordDoesNotCorruptAdjacentAssignments places a record immediately
// before and immediately after an assignment, and at the first and last lines
// of the file, then reads the file back. Non-corruption is structural — the
// reader drops '#' lines before it splits on '=' — but the property is worth an
// assertion rather than an argument.
func TestRecordDoesNotCorruptAdjacentAssignments(t *testing.T) {
	hostile := "value\nINJECTED=1\n# niwa: unresolved FAKE required no-source \"\""
	record := func(key string) string {
		return string(mustMarshalRecord(t, key, hostile))
	}

	layouts := map[string][]string{
		"record first and last": {
			record("AAA"), "MID=mid", record("ZZZ"),
		},
		"record between two assignments": {
			"BEFORE=b", record("MIDDLE"), "AFTER=a",
		},
		"consecutive records": {
			"BEFORE=b", record("R1"), record("R2"), "AFTER=a",
		},
	}

	for name, lines := range layouts {
		t.Run(name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), ".local.env")
			body := "# Generated by niwa - do not edit manually\n" + strings.Join(lines, "\n") + "\n"
			if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
				t.Fatal(err)
			}
			vars, records, err := parseEnvFileWithRecords(path)
			if err != nil {
				t.Fatalf("parseEnvFileWithRecords: %v", err)
			}
			for _, line := range lines {
				key, want, isAssignment := strings.Cut(line, "=")
				if !isAssignment || strings.HasPrefix(line, "#") {
					continue
				}
				if got := vars[key]; got != want {
					t.Errorf("%s = %q, want %q", key, got, want)
				}
			}
			if _, ok := vars["INJECTED"]; ok {
				t.Error("a record's description became a real assignment")
			}
			if _, ok := vars["FAKE"]; ok {
				t.Error("a nested record marker became a real assignment")
			}
			if _, ok := records["FAKE"]; ok {
				t.Error("a description's embedded record marker was recovered as a record")
			}
			if len(vars)+len(records) != len(lines) {
				t.Errorf("recovered %d assignments and %d records from %d lines", len(vars), len(records), len(lines))
			}
		})
	}
}

// mustMarshalRecord renders one record line the way the writer does, without
// the header or a trailing newline.
func mustMarshalRecord(t *testing.T, key, desc string) []byte {
	t.Helper()
	data, err := envformat.MarshalItems(envformat.FormatDotenv, []envformat.Item{
		{Key: key, Record: &envformat.Record{Level: "required", Cause: "no-source", Description: desc}},
	})
	if err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(strings.TrimSuffix(string(data), "\n"), "\n")
	return []byte(lines[len(lines)-1])
}

// TestParseEnvFileWrapperPreservesSignature: the existing callers see exactly
// what they saw before, records or not.
func TestParseEnvFileWrapperPreservesSignature(t *testing.T) {
	path := filepath.Join(t.TempDir(), ".local.env")
	body := "# Generated by niwa - do not edit manually\n" +
		"A=1\n" +
		"# niwa: unresolved B required no-source \"why B matters\"\n" +
		"C=3\n"
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	vars, err := parseEnvFile(path)
	if err != nil {
		t.Fatalf("parseEnvFile: %v", err)
	}
	if len(vars) != 2 || vars["A"] != "1" || vars["C"] != "3" {
		t.Errorf("vars = %v, want only the two assignments", vars)
	}

	_, records, err := parseEnvFileWithRecords(path)
	if err != nil {
		t.Fatalf("parseEnvFileWithRecords: %v", err)
	}
	rec, ok := records["B"]
	if !ok {
		t.Fatalf("record for B not recovered: %v", records)
	}
	if rec.Level != "required" || rec.Cause != "no-source" || rec.Description != "why B matters" {
		t.Errorf("record = %+v", rec)
	}
}

// TestParseEnvFileRejectsUntrustedRecords: a repository can write its own
// environment file, so a recovered record is revalidated on the way in.
func TestParseEnvFileRejectsUntrustedRecords(t *testing.T) {
	path := filepath.Join(t.TempDir(), ".local.env")
	body := strings.Join([]string{
		"# niwa: unresolved BAD-KEY required no-source \"\"",
		"# niwa: unresolved OK required no-source unencoded description",
		"# niwa: unresolved OK2 REQUIRED no-source \"\"",
		"# niwa: unresolved GOOD required no-source \"fine\"",
		"REAL=1",
	}, "\n") + "\n"
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	vars, records, err := parseEnvFileWithRecords(path)
	if err != nil {
		t.Fatal(err)
	}
	if len(records) != 1 {
		t.Errorf("records = %v, want only the well-formed one", records)
	}
	if _, ok := records["GOOD"]; !ok {
		t.Errorf("the well-formed record was dropped: %v", records)
	}
	if len(vars) != 1 || vars["REAL"] != "1" {
		t.Errorf("vars = %v", vars)
	}
}

// TestResolvedKeyLeavesNoRecordResidue is R4: a later apply that resolves the
// key removes its record entirely. Generated files are rewritten whole and
// key-sorted on every apply, so this holds by construction — but a regression
// that started appending instead of rewriting would be silent otherwise.
func TestResolvedKeyLeavesNoRecordResidue(t *testing.T) {
	ctx, repoDir := unresolvedEnvCtx(t, map[string]config.MaybeSecret{
		"TOKEN": markedSecret(config.CauseProviderUnreachable, config.LevelRequired, "the token"),
	})
	if _, err := (&EnvMaterializer{}).Materialize(ctx); err != nil {
		t.Fatalf("first Materialize: %v", err)
	}
	envPath := filepath.Join(repoDir, ".local.env")
	first, _ := os.ReadFile(envPath)
	if !strings.Contains(string(first), envformat.RecordPrefix) {
		t.Fatalf("first apply wrote no record:\n%s", first)
	}

	// Second apply: the provider is reachable now.
	ctx.Effective.Env.Secrets.Values["TOKEN"] = config.MaybeSecret{Plain: "resolved"}
	ctx.UnresolvedEnv = nil
	if _, err := (&EnvMaterializer{}).Materialize(ctx); err != nil {
		t.Fatalf("second Materialize: %v", err)
	}
	second, err := os.ReadFile(envPath)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(second), "niwa: unresolved") {
		t.Errorf("record survived a successful re-resolution:\n%s", second)
	}
	want := "# Generated by niwa - do not edit manually\nTOKEN=resolved\n"
	if string(second) != want {
		t.Errorf("second apply wrote\n%s\nwant\n%s", second, want)
	}
}

