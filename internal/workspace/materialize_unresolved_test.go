// TestApplyWritesRecordForEveryUnresolvedKey is the whole chain against a real
// apply, in the shape this work exists to serve: every declared key comes back
// unresolved, so the value map is empty — and the generated file must still
// exist and account for each key rather than being skipped entirely.
//
// The provider here is reachable and simply holds nothing, because that is the
// shortfall the test fixtures can produce; the materializer treats every mark
// the same way regardless of its cause.
func TestApplyWritesRecordForEveryUnresolvedKey(t *testing.T) {
	withFakeVaultBackend(t)

	configTOML := `
[workspace]
name = "no-provider-ws"

[[sources]]
org = "testorg"

[groups.default]
repos = ["app"]

[vault.provider]
kind = "fake"

[env.secrets]
ANTHROPIC_API_KEY = "vault://ANTHROPIC_API_KEY"
TAVILY_API_KEY = "vault://TAVILY_API_KEY"

[env.secrets.recommended]
ANTHROPIC_API_KEY = "API key for Claude Code sessions"
`

	tmpDir := t.TempDir()
	niwaDir := filepath.Join(tmpDir, ".niwa")
	if err := os.MkdirAll(niwaDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(niwaDir, "workspace.toml"), []byte(configTOML), 0o644); err != nil {
		t.Fatal(err)
	}

	parsed, err := config.Load(filepath.Join(niwaDir, "workspace.toml"))
	if err != nil {
		t.Fatalf("config.Load: %v", err)
	}

	mockClient := &mockGitHubClient{
		repos: map[string][]github.Repo{
			"testorg": {{Name: "app", SSHURL: "git@github.com:testorg/app.git"}},
		},
	}
	groupDir := filepath.Join(tmpDir, "no-provider-ws", "default")
	if err := os.MkdirAll(filepath.Join(groupDir, "app", ".git"), 0o755); err != nil {
		t.Fatal(err)
	}

	applier := NewApplier(mockClient)
	applier.Cloner = &Cloner{}
	if _, err := applier.Create(context.Background(), parsed.Config, niwaDir, tmpDir, parsed.Config.Workspace.Name); err != nil {
		t.Fatalf("apply must survive a host with no vault backend, got: %v", err)
	}

	envPath := filepath.Join(groupDir, "app", ".local.env")
	data, err := os.ReadFile(envPath)
	if err != nil {
		t.Fatalf("a repo whose keys are all unresolved must still get a file: %v", err)
	}
	want := "# Generated by niwa - do not edit manually\n" +
		"# niwa: unresolved ANTHROPIC_API_KEY recommended key-not-found \"API key for Claude Code sessions\"\n" +
		"# niwa: unresolved TAVILY_API_KEY unspecified key-not-found \"\"\n"
	if string(data) != want {
		t.Errorf("generated file =\n%s\nwant\n%s", data, want)
	}

	// Reading the file back yields no assignments at all: a record is a
	// whole-line comment, so nothing here can be mistaken for a value.
	vars, records, err := parseEnvFileWithRecords(envPath)
	if err != nil {
		t.Fatal(err)
	}
	if len(vars) != 0 {
		t.Errorf("records produced assignments on read-back: %v", vars)
	}
	if len(records) != 2 {
		t.Errorf("recovered %d records, want 2: %v", len(records), records)
	}
}
